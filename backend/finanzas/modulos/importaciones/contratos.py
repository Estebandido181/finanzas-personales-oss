@dataclass(frozen=True)
class MovimientoExcel:
    """Un movimiento leído del Excel del banco.

    - ``fecha``: día del movimiento (el banco no da hora).
    - ``monto_centavos``: entero con signo, en centavos. Negativo = sale de la
      cuenta (gasto); positivo = entra. ``-5000.5`` -> ``-500050``.
    - ``descripcion``: texto del banco tal como viene, solo sin espacios al
      inicio ni al final. Los espacios internos NO se colapsan
      (``"COMPRA EN  TIENDA EJEMPLO"`` queda igual): es lo que muestra el
      banco y la conciliación empareja por día y monto, no por descripción.
      Suele venir recortado a unos 30 caracteres.

    - ``referencia``: los últimos 4 dígitos de la columna ``Referencia`` como
      ``"*1234"`` (D37), o ``None`` si viene vacía o sin formato. Nunca el
      número completo.
    - ``referencia_sin_formato``: ``True`` si la celda traía algo que no es un
      número de al menos 4 dígitos (letras, signos, menos de 4 dígitos). La
      fila entra igual, sin destino (D45); la conciliación en seco las cuenta.
    """

    fecha: date
    monto_centavos: int
    descripcion: str
    referencia: str | None = None
    referencia_sin_formato: bool = False


