class _Efecto:
    """Cuánto movió el saldo una respuesta, visto desde un ajuste.

    ``diferencia``: lo que cambió al aplicar la respuesta. Si se confirmó un
    aviso que llegó **después** de ese ajuste (id mayor), el ajuste no lo
    tenía en cuenta pero sí el movimiento real del banco: para él cuenta el
    efecto completo de la fila (la diferencia más lo que sumó el aviso al
    llegar). Así el aviso no se cuenta dos veces.
    """

    def __init__(self, diferencia: int, aviso_id: int | None = None, del_aviso: int = 0,
                 movimiento_id: int | None = None):
        self.diferencia, self.aviso_id, self.del_aviso = diferencia, aviso_id, del_aviso
        self.movimiento_id = movimiento_id

    def para(self, ajuste_id: int) -> int:
        if self.aviso_id is not None and ajuste_id < self.aviso_id:
            return self.diferencia + self.del_aviso
        return self.diferencia



